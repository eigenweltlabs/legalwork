#!/usr/bin/env node
/**
 * Generates apps/app/src/react-app/domains/session/artifacts/office-fonts.css.
 *
 * The Office viewers used to resolve a document's fonts against Google Fonts,
 * which told Google the typefaces inside a client's file. That lookup is off
 * (setGoogleFontsEnabled(false) for .docx, a patch for .pptx), so the faces it
 * used to fetch are bundled instead: one @font-face per Office family aliasing
 * it to the open substitute the editor itself picked.
 *
 * Two kinds of substitute, and the difference matters for a redlining tool:
 *
 *   - METRIC_COMPATIBLE (6 of 23): Carlito, Caladea, Arimo, Tinos and Cousine
 *     were drawn to the advance widths of Calibri, Cambria, Arial/Helvetica,
 *     Times New Roman and Courier New. Every line breaks where Word breaks it,
 *     so pagination holds.
 *   - Everything else: a similar-looking face with its own widths. Georgia is
 *     not Times, Verdana is not Open Sans. The text is readable and close in
 *     colour, but lines re-wrap and page counts can differ from Word.
 *
 * FONT_MAPPING mirrors the table inside @eigenpal/docx-editor-core, so a
 * document renders exactly as it did when the substitute came off the network —
 * this bundles what was already being fetched, it does not improve on it.
 * `local()` comes first in every rule, so a machine that really has the font
 * uses it and no file is fetched at all.
 *
 * Run: node scripts/gen-office-fonts.mjs
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ARTIFACTS = "apps/app/src/react-app/domains/session/artifacts";
const OUT = resolve(repoRoot, ARTIFACTS, "office-fonts.css");
// The family list, for code that has to know which fonts the CSS already
// covers (the font-consent prompt). Generated alongside so the two cannot drift.
const OUT_FAMILIES = resolve(repoRoot, ARTIFACTS, "office-font-families.ts");

/** Office family -> open substitute. Mirrors FONT_MAPPING in the editor core. */
const FONT_MAPPING = {
  "Calibri": "carlito",
  "Cambria": "caladea",
  "Arial": "arimo",
  "Helvetica": "arimo",
  "Times New Roman": "tinos",
  "Georgia": "tinos",
  "Courier New": "cousine",
  "Garamond": "eb-garamond",
  "Book Antiqua": "eb-garamond",
  "Palatino": "eb-garamond",
  "Palatino Linotype": "eb-garamond",
  "Verdana": "open-sans",
  "Tahoma": "open-sans",
  "Lucida Sans": "open-sans",
  "Segoe UI": "open-sans",
  "Trebuchet MS": "source-sans-pro",
  "Century Gothic": "poppins",
  "Franklin Gothic": "libre-franklin",
  "Impact": "anton",
  "Comic Sans MS": "comic-neue",
  "Consolas": "inconsolata",
  "Lucida Console": "inconsolata",
  "Monaco": "fira-code",
};

/**
 * The mappings whose substitute shares the original's advance widths, so line
 * and page breaks match Word. Per pair, not per substitute: Tinos is metric
 * compatible with Times New Roman but not with Georgia, which is a wider face.
 */
const METRIC_COMPATIBLE = new Set([
  "Calibri", "Cambria", "Arial", "Helvetica", "Times New Roman", "Courier New",
]);

/** unicode-range values, copied from fontsource's own per-subset CSS. */
const SUBSETS = {
  "latin":
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  "latin-ext":
    "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
};

/** Documents address regular and bold; obliques are synthesized when missing. */
const WANTED_WEIGHTS = [400, 700];

function fontsourceDir(clone) {
  const base = resolve(repoRoot, "node_modules/.pnpm");
  const match = readdirSync(base).find((entry) => entry.startsWith(`@fontsource+${clone}@`));
  if (!match) throw new Error(`@fontsource/${clone} is not installed`);
  return resolve(base, match, "node_modules/@fontsource", clone, "files");
}

/** What this clone actually ships, as {subset: {style: [weights]}}. */
function availableFaces(clone) {
  const faces = {};
  for (const name of readdirSync(fontsourceDir(clone))) {
    const m = name.match(new RegExp(`^${clone}-([a-z-]+)-(\\d+)-(normal|italic)\\.woff2$`));
    if (!m) continue;
    const [, subset, weight, style] = m;
    if (!SUBSETS[subset]) continue;
    ((faces[subset] ??= {})[style] ??= []).push(Number(weight));
  }
  return faces;
}

/** Nearest shipped weight, so a family without 700 still gets a bold face. */
function nearestWeight(available, wanted) {
  return available.reduce((best, w) =>
    Math.abs(w - wanted) < Math.abs(best - wanted) ? w : best,
  );
}

const lines = [
  "/* AUTO-GENERATED by scripts/gen-office-fonts.mjs — DO NOT EDIT BY HAND. */",
  "/*",
  " * Office font aliases for the .docx, .xlsx and .pptx viewers.",
  " *",
  " * A document names fonts like Calibri or Times New Roman that only exist on",
  " * Windows. Rather than fetch a substitute from Google Fonts — which would",
  " * disclose the typefaces inside a client's file — each family is aliased to",
  " * the open substitute that the editor used to download.",
  " *",
  " * Each rule below says which kind it is. Six mappings are metric compatible:",
  " * same advance widths, so lines and pages break as in Word. The rest only",
  " * look similar, so text stays readable but can re-wrap.",
  " *",
  " * `local()` is first in every rule: a machine that really has the font uses",
  " * it and nothing is fetched at all.",
  " */",
  "",
];

let ruleCount = 0;
for (const [family, clone] of Object.entries(FONT_MAPPING)) {
  const faces = availableFaces(clone);
  const rules = [];
  for (const [subset, range] of Object.entries(SUBSETS)) {
    const styles = faces[subset];
    if (!styles) continue;
    for (const style of ["normal", "italic"]) {
      const weights = styles[style];
      if (!weights?.length) continue; // no italic cut: let the browser oblique it
      for (const wanted of WANTED_WEIGHTS) {
        const actual = nearestWeight(weights, wanted);
        const file = `@fontsource/${clone}/files/${clone}-${subset}-${actual}-${style}.woff2`;
        rules.push(
          `@font-face { font-family: "${family}"; font-style: ${style}; font-weight: ${wanted}; ` +
            `font-display: swap; src: local("${family}"), url("${file}") format("woff2"); ` +
            `unicode-range: ${range}; }`,
        );
      }
    }
  }
  const kind = METRIC_COMPATIBLE.has(family)
    ? "metric compatible: same widths, breaks as in Word"
    : "look-alike: different widths, lines can re-wrap";
  lines.push(`/* ${family} -> ${clone} (${kind}) */`, ...rules, "");
  ruleCount += rules.length;
}

writeFileSync(OUT, lines.join("\n"));

const families = Object.keys(FONT_MAPPING);
writeFileSync(
  OUT_FAMILIES,
  [
    "// AUTO-GENERATED by scripts/gen-office-fonts.mjs — DO NOT EDIT BY HAND.",
    "",
    "/**",
    " * Office families that office-fonts.css already aliases to a bundled clone.",
    " * A document font in this set always renders locally, so it never needs to",
    " * be fetched and the font-consent prompt skips it.",
    " */",
    "export const BUNDLED_OFFICE_FONTS: ReadonlySet<string> = new Set([",
    ...families.map((f) => `  ${JSON.stringify(f)},`),
    "]);",
    "",
  ].join("\n"),
);

console.log(
  `wrote ${OUT} (${families.length} families, ${ruleCount} @font-face rules)\n` +
    `wrote ${OUT_FAMILIES} (${families.length} families)`,
);
