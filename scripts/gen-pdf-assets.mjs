// Embed the pinned PDF.js fonts, CMaps and decoders so compiled server binaries
// can render multilingual PDFs without node_modules or network asset downloads.
import { createRequire } from 'node:module';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'apps/server/package.json'));
const pdf = dirname(require.resolve('pdfjs-dist/package.json'));
const entries = {};
for (const folder of ['cmaps', 'standard_fonts', 'wasm']) {
  for (const file of readdirSync(join(pdf, folder)).sort()) entries[`${folder}/${file}`] = readFileSync(join(pdf, folder, file)).toString('base64');
}
entries.LICENSE = readFileSync(join(pdf, 'LICENSE')).toString('base64');
const packed = gzipSync(JSON.stringify(entries), {level:9}).toString('base64');
const code = `// Generated by scripts/gen-pdf-assets.mjs from pdfjs-dist. Includes upstream license files.\nimport { gunzipSync } from "node:zlib";\nimport { z } from "zod";\nconst packed = ${JSON.stringify(packed)};\nlet assets: Record<string, string> | undefined;\nexport function pdfAsset(name: string): Uint8Array {\n  assets ??= z.record(z.string(), z.string()).parse(JSON.parse(gunzipSync(Buffer.from(packed, "base64")).toString("utf8")));\n  const data = assets[name];\n  if (!data) throw new Error("Unknown PDF rendering asset");\n  return new Uint8Array(Buffer.from(data, "base64"));\n}\n`;
const path = join(root, 'apps/server/src/document-preparation/pdf-assets.ts');
writeFileSync(path, code);
console.log(`Generated embedded PDF assets (${Math.round(code.length/1024)} KiB).`);
