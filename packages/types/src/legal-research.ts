export const researchWebsite = z.string().trim().max(2000).url().refine(value => {
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password && !url.hash;
  } catch { return false; }
}, "Enter a complete HTTPS address without embedded credentials or a fragment.");
const country = z.string().refine(value => value === "OTHER" || legalResearchCountries.includes(value));
const passwordId = z.string().uuid();
const name = z.string().trim().min(1).max(80).refine(value => !/[\r\n\x00-\x1f]/.test(value));
export const researchDatabaseSetupSchema = z.union([
  z.object({ providerId: z.string().min(1).max(80), country, passwordId, loginUrl: researchWebsite.optional() }).strict(),
  z.object({ name, researchUrl: researchWebsite, loginUrl: researchWebsite, country, passwordId }).strict(),
]);
export type ResearchDatabaseSetup = z.infer<typeof researchDatabaseSetupSchema>;
