import { afterEach, expect, test } from "bun:test";
import { QueryObserver } from "@tanstack/react-query";
import type { ProviderListView } from "../src/app/types";
import { createProviderAuthStore } from "../src/react-app/domains/connections/provider-auth/store";
import { fetchProviderList, ensureProviderListQuery, PROVIDER_LIST_CACHE_MS, providerListQueryKey, refreshProviderListQueries } from "../src/react-app/infra/provider-list-query";
import { getReactQueryClient } from "../src/react-app/infra/query-client";
import { nativeProviderFixture } from "./native-provider-fixture";
const cleanups: Array<() => void> = [];
afterEach(() => { cleanups.splice(0).forEach(cleanup => cleanup()); getReactQueryClient().clear(); });
const providerList = (connected: string[]): ProviderListView => ({ all: [], connected, default: {} });
test("native location reload refreshes the same catalog cache the composer observes once", async () => {
  const connected = new Set<string>();
  const fixture = nativeProviderFixture({ connected, onReload: () => { connected.add("openai"); } });
  cleanups.push(fixture.stop);
  const baseUrl = fixture.baseUrl;
  const directory = "/preview";
  const composer = new QueryObserver(getReactQueryClient(), { queryKey: providerListQueryKey({ baseUrl, directory }), queryFn: () => fetchProviderList({ client: fixture.client, baseUrl, directory }), staleTime: PROVIDER_LIST_CACHE_MS });
  cleanups.push(composer.subscribe(() => {}));
  await composer.refetch();
  expect(composer.getCurrentResult().data?.connected).toEqual([]);
  const store = createProviderAuthStore({ client: () => fixture.client, baseUrl: () => baseUrl, providers: () => [], providerDefaults: () => ({}), providerConnectedIds: () => [], disabledProviders: () => [], selectedWorkspaceDisplay: () => ({ id: "ws", name: "Workspace", path: directory, workspaceType: "local" }), selectedWorkspaceRoot: () => directory, runtimeWorkspaceId: () => null,
    legalworkServer: { getSnapshot: () => ({ legalworkServerStatus: "disconnected", legalworkServerClient: null, legalworkServerCapabilities: null }) }, setProviders: () => {}, setProviderDefaults: () => {}, setProviderConnectedIds: () => {}, setDisabledProviders: () => {}, markOpencodeConfigReloadRequired: () => {} });
  fixture.calls.splice(0);
  await store.refreshProviders({ dispose: true });
  expect(composer.getCurrentResult().data?.connected).toEqual(["openai"]);
  expect(fixture.calls.filter(call => call.path === "/api/provider")).toHaveLength(1);
  await store.refreshProviders();
  expect((await ensureProviderListQuery(getReactQueryClient(), { client: fixture.client, baseUrl, directory })).connected).toEqual(["openai"]);
  expect(fixture.calls.filter(call => call.path === "/api/provider")).toHaveLength(1);
});
test("an expired picker cache fetches one native catalog per endpoint and location", async () => {
  const fixture = nativeProviderFixture(); cleanups.push(fixture.stop); fixture.connected.add("openai");
  const directory = "/preview";
  getReactQueryClient().setQueryData(providerListQueryKey({ baseUrl: fixture.baseUrl, directory }), providerList([]), { updatedAt: Date.now() - PROVIDER_LIST_CACHE_MS - 1 });
  expect((await ensureProviderListQuery(getReactQueryClient(), { client: fixture.client, baseUrl: fixture.baseUrl, directory })).connected).toEqual(["openai"]);
  await ensureProviderListQuery(getReactQueryClient(), { client: fixture.client, baseUrl: fixture.baseUrl, directory });
  expect(fixture.calls.filter(call => call.path === "/api/provider")).toHaveLength(1);
  await ensureProviderListQuery(getReactQueryClient(), { client: fixture.client, baseUrl: `${fixture.baseUrl}/other`, directory });
  expect(fixture.calls.filter(call => call.path === "/api/provider")).toHaveLength(2);
});
test("reload drops inactive workspace snapshots and refreshes active ones once", async () => {
  const queryClient = getReactQueryClient();
  const inactive = providerListQueryKey({ baseUrl: "http://inactive", directory: "/other" });
  queryClient.setQueryData(inactive, providerList([]));
  let calls = 0;
  const key = providerListQueryKey({ baseUrl: "http://active", directory: "/preview" });
  const observer = new QueryObserver(queryClient, { queryKey: key, queryFn: async () => { calls += 1; return providerList([]); }, staleTime: Infinity });
  cleanups.push(observer.subscribe(() => {})); await observer.refetch(); calls = 0;
  await refreshProviderListQueries(queryClient);
  expect(calls).toBe(1); expect(queryClient.getQueryData(inactive)).toBeUndefined();
});
