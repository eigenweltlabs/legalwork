import { fileURLToPath } from "node:url";

const result = await Bun.build({
  entrypoints: [fileURLToPath(new URL("../src/tool-image-raster-worker.ts", import.meta.url))],
  target: "node", format: "cjs", minify: true,
});
if (!result.success || result.outputs.length !== 1) throw new Error(result.logs.join("\n") || "Expected one standalone image worker bundle.");
await Bun.write(new URL("../src/tool-image-raster-code.ts", import.meta.url),
  `// Generated by scripts/gen-tool-image-raster-code.ts; do not edit.\nexport const TOOL_IMAGE_RASTER_CODE = ${JSON.stringify(await result.outputs[0].text())};\n`);
